def convert_base(number_str: str, from_base: int, to_base: int) -> str:
    # --- ШАГ 1: ПРОВЕРКА КОРРЕКТНОСТИ СИСТЕМ ---
    # Проверяем, входят ли системы счисления в допустимый диапазон от 2 до 36.
    if not (2 <= from_base <= 36 and 2 <= to_base <= 36):
        # Если системы счисления некорректны, вызываем ошибку и останавливаем программу.
        raise ValueError("Основание системы счисления должно быть от 2 до 36!")

    # --- ШАГ 2: ОБРАБОТКА ЗНАКА И РЕГИСТРА ---
    # Переводим всю строку в нижний регистр, чтобы буквы 'A' и 'a' воспринимались одинаково.
    number_str = number_str.lower()
    # Запоминаем, начинается ли строка с минуса (True, если число отрицательное).
    is_negative = number_str.startswith('-')
    
    # Если минус есть, убираем его из строки (срезаем первый символ), чтобы он не мешал математике.
    if is_negative:
        number_str = number_str[1:]

    # Создаем полный алфавит символов. Индекс каждого символа равен его «стоимости» (например, 'a' = 10).
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"

    # --- ШАГ 3: ПЕРЕВОД ИЗ ИСХОДНОЙ СИСТЕМЫ В 10-РИЧНУЮ ---
    # Переменная, где мы по кусочкам соберем наше число в привычном десятичном виде.
    decimal_number = 0
    # Узнаем длину строки, чтобы правильно определять степени разрядов.
    length = len(number_str)
    
    # Запускаем цикл по каждому символу строки. enumerate дает нам индекс символа (i) и сам символ (char).
    for i, char in enumerate(number_str):
        # Находим числовое значение символа, отыскав его позицию в нашем алфавите digits.
        value = digits.index(char)
        # Вычисляем степень для этого разряда (самый левый разряд имеет наибольшую степень).
        power = length - 1 - i
        # Умножаем значение цифры на основание системы в нужной степени и добавляем к общей сумме.
        decimal_number += value * (from_base ** power)

    # --- ШАГ 4: ОБРАБОТКА НУЛЯ ---
    # Если в итоге получилось десятичное число 0, то в любой целевой системе это тоже будет просто "0".
    if decimal_number == 0:
        return "0"

    # --- ШАГ 5: ПЕРЕВОД ИЗ 10-РИЧНОЙ СИСТЕМЫ В ЦЕЛЕВУЮ ---
    # Создаем пустую строку, куда будем записывать остатки от деления на целевую систему счисления.
    result_str = ""
    
    # Запускаем цикл деления, который работает, пока наше десятичное число больше нуля.
    while decimal_number > 0:
        # Находим остаток от деления десятичного числа на основание целевой системы счисления.
        remainder = decimal_number % to_base
        # Переводим остаток в символ с помощью алфавита digits и приклеиваем его В НАЧАЛО строки.
        result_str = digits[remainder] + result_str
        # Делим число нацело на основание целевой системы, уменьшая его для следующего шага цикла.
        decimal_number //= to_base

    # --- ШАГ 6: СБОРКА ФИНАЛЬНОГО РЕЗУЛЬТАТА ---
    # Если изначально число было отрицательным, склеиваем знак минус и получившуюся строку.
    if is_negative:
        return "-" + result_str
    # Если число было положительным, возвращаем результат в чистом виде.
    return result_str

# 1. Переводим число 255 из 10-ричной в 16-ричную (проверим себя)
print(convert_base("255", 10, 16))  # Выведет: 'ff'

# 2. Переводим число "10110" из двоичной в восьмеричную напрямую
print(convert_base("10110", 2, 8))   # Выведет: '26'

# 3. Экзотический перевод: из 5-ричной системы в 36-ричную
print(convert_base("4444", 5, 36))   # Выведет: 'hc'

# 4. Работа с отрицательными числами
print(convert_base("-ff", 16, 2))    # Выведет: '-11111111'
