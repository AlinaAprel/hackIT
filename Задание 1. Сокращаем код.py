# range(1, 10, 2) (начало, конец, шаг). Запиши алгоритм используя 3 аргументаы

import turtle

t = turtle.Turtle()
t.speed(3)  # Делаем черепашку быстрее, чтобы не ждать долго


t.forward(100)  # Едем вперед на 100 шагов
t.left(90)  # Поворачиваем налево на 90 градусов

t.forward(100)
t.left(90)

t.forward(100)
t.left(90)

t.forward(100)
t.left(90)  

turtle.done()