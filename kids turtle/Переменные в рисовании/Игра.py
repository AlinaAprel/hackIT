import turtle  # Подключаем модуль графики черепашки
import random  # Подключаем модуль для случайных чисел

# --- НАСТРОЙКА ОКНА ---
window = turtle.Screen()  # Создаем игровое окно
window.title("Космическая Черепашка: Охотник за Кристаллами")  # Пишем название игры в рамке окна
window.bgcolor("navy")  # Заливаем фон темно-синим цветом (как открытый космос)
window.setup(width=600, height=600)  # Устанавливаем размер окна 600 на 600 пикселей

# --- ПЕРЕМЕННЫЕ ИГРЫ ---
# ЗАДАНИЕ 1: Создай переменную score и положи в неё 0 очков для старта
score = 0  # Впиши число 0 вместо прочерка!

# ЗАДАНИЕ 2: Создай переменную step (размер шага черепашки) равную 20
step = 20  # Впиши число 20 вместо прочерка!

target_score = 5  # Переменная цели: сколько кристаллов нужно собрать для победы

# --- СОЗДАЕМ ИГРОКА (ЧЕРЕПАШКУ) ---
player = turtle.Turtle()  # Создаем объект нашей черепашки
player.shape("turtle")  # Выбираем костюм настоящей черепахи
player.color("lime")  # Красим черепашку в ярко-зеленый цвет
player.penup()  # Поднимаем перо, чтобы черепашка не чертила линии при беге
player.speed(0)  # Устанавливаем самую быструю скорость анимации

# --- СОЗДАЕМ ЗОЛОТОЙ КРИСТАЛЛ ---
crystal = turtle.Turtle()  # Создаем второй объект — кристалл
crystal.shape("circle")  # Делаем кристалл круглым
crystal.color("gold")  # Красим кристалл в сияющий золотой цвет
crystal.penup()  # Поднимаем перо у кристалла
crystal.speed(0)  # Кристалл появляется моментально
crystal.goto(100, 100)  # Отправляем кристалл на начальную позицию

# --- СОЗДАЕМ ТЕКСТ ДЛЯ СЧЕТА ---
pen = turtle.Turtle()  # Создаем невидимую черепашку-писаря для счета
pen.hideturtle()  # Прячем саму стрелочку писаря, нужен только текст
pen.penup()  # Поднимаем перо
pen.color("white")  # Цвет текста счета будет белым
pen.goto(0, 250)  # Перемещаем текст наверх по центру
pen.write("Собрано кристаллов: " + str(score), align="center", font=("Arial", 16, "bold"))  # Печатаем счет

# --- ПРОВЕРКА СБОРА КРИСТАЛЛА ---
def check_crystal():  # Создаем функцию проверки столкновения
    global score, step  # Разрешаем изменять переменные score и step внутри этой функции
    if player.distance(crystal) < 25:  # Если расстояние от черепашки до кристалла меньше 25 пикселей:
        
        # ЗАДАНИЕ 3: Увеличь переменную score на 1 очко
        score = score + 1  # Впиши число 1 вместо прочерка!
        
        # ЗАДАНИЕ 4: Сделай бонус к скорости! Увеличь переменную step на 2
        step = step + 2  # Впиши число 2 вместо прочерка (черепашка ускорится!)
        
        new_x = random.randint(-220, 220)  # Выбираем случайную координату X для нового кристалла
        new_y = random.randint(-220, 220)  # Выбираем случайную координату Y для нового кристалла
        crystal.goto(new_x, new_y)  # Телепортируем кристалл на новое случайное место
        pen.clear()  # Стираем старый текст счета
        pen.write("Собрано кристаллов: " + str(score), align="center", font=("Arial", 16, "bold"))  # Пишем обновленный счет
        
        # ЗАДАНИЕ 5: Проверь условие победы! Сравни переменную score с target_score
        if score == target_score:  # Впиши переменную target_score вместо прочерка!
            pen.goto(0, 0)  # Перемещаем текст победы прямо в центр экрана
            pen.write("ПОБЕДА! КОСМОС СПАСЕН!", align="center", font=("Arial", 22, "bold"))  # Выводим поздравление

# --- УПРАВЛЕНИЕ ЧЕРЕПАШКОЙ ---
def go_up():  # Функция бега вверх
    player.setheading(90)  # Поворачиваем черепашку на север (90 градусов)
    player.forward(step)  # Черепашка делает шаг вперед на значение переменной step
    check_crystal()  # Вызываем проверку: не подобрали ли кристалл

def go_down():  # Функция бега вниз
    player.setheading(270)  # Поворачиваем черепашку на юг (270 градусов)
    player.forward(step)  # Черепашка делает шаг вперед на значение переменной step
    check_crystal()  # Вызываем проверку: не подобрали ли кристалл

def go_left():  # Функция бега влево
    player.setheading(180)  # Поворачиваем черепашку на запад (180 градусов)
    player.forward(step)  # Черепашка делает шаг вперед на значение переменной step
    check_crystal()  # Вызываем проверку: не подобрали ли кристалл

def go_right():  # Функция бега вправо
    player.setheading(0)  # Поворачиваем черепашку на восток (0 градусов)
    player.forward(step)  # Черепашка делает шаг вперед на значение переменной step
    check_crystal()  # Вызываем проверку: не подобрали ли кристалл

# --- СЛУШАЕМ КЛАВИАТУРУ ---
window.listen()  # Заставляем игровое окно реагировать на нажатия клавиш
window.onkey(go_up, "Up")  # При нажатии стрелки "Вверх" вызываем команду go_up
window.onkey(go_down, "Down")  # При нажатии стрелки "Вниз" вызываем команду go_down
window.onkey(go_left, "Left")  # При нажатии стрелки "Влево" вызываем команду go_left
window.onkey(go_right, "Right")  # При нажатии стрелки "Вправо" вызываем команду go_right

turtle.done()  # Не закрываем окно, пока игрок сам не нажмет на крестик