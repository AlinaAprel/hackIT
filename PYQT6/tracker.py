import sys  # Импортируем модуль sys для управления параметрами среды и выхода из приложения
from PySide6.QtWidgets import (  # Начинаем импорт необходимых графических компонентов из библиотеки PySide6
    QApplication,  # Импортируем главный класс приложения, управляющий его логикой и настройками
    QMainWindow,  # Импортируем класс основного окна, который предоставляет каркас для интерфейса
    QWidget,  # Импортируем базовый класс для всех элементов интерфейса (виджетов)
    QVBoxLayout,  # Импортируем вертикальный макет для автоматического размещения элементов друг под другом
    QHBoxLayout,  # Импортируем горизонтальный макет для размещения элементов слева направо
    QLineEdit,  # Импортируем однострочное текстовое поле для ввода данных пользователем
    QPushButton,  # Импортируем стандартную нажимаемую кнопку
    QListWidget,  # Импортируем виджет списка для отображения и выбора элементов
    QMessageBox,  # Импортируем класс для создания всплывающих диалоговых окон с сообщениями
)  # Завершаем импорт компонентов PySide6


class TodoApp(QMainWindow):  # Создаем наш собственный класс окна TodoApp, наследуясь от QMainWindow

    def __init__(self):  # Определяем конструктор класса, который вызывается при создании объекта
        super().__init__()  # Вызываем конструктор родительского класса QMainWindow для его правильной инициализации
        self.setWindowTitle(
            "Мой учебный To-Do Проект"
        )  # Устанавливаем текст, который будет отображаться в заголовке окна
        self.resize(
            400, 500
        )  # Задаем начальные размеры окна приложения: ширина 400 пикселей, высота 500 пикселей

        self.central_widget = (
            QWidget()
        )  # Создаем базовый виджет, который послужит контейнером для всего содержимого
        self.setCentralWidget(
            self.central_widget
        )  # Назначаем созданный контейнер главным (центральным) виджетом нашего QMainWindow

        self.main_layout = (
            QVBoxLayout()
        )  # Создаем главный вертикальный макет, чтобы элементы окна шли сверху вниз
        self.input_layout = (
            QHBoxLayout()
        )  # Создаем вспомогательный горизонтальный макет для строки ввода и кнопки добавления

        self.task_input = (
            QLineEdit()
        )  # Создаем поле ввода текста, куда пользователь будет писать название задачи
        self.task_input.setPlaceholderText(
            "Введите новую задачу..."
        )  # Добавляем серый текст-подсказку внутрь пустого поля ввода

        self.add_button = (
            QPushButton("Добавить")
        )  # Создаем кнопку с надписью "Добавить" для создания новой задачи
        self.add_button.clicked.connect(
            self.add_task
        )  # Связываем сигнал клика по кнопке со слотом (методом) self.add_task

        self.input_layout.addWidget(
            self.task_input
        )  # Помещаем текстовое поле ввода в горизонтальный макет (оно займет левую часть)
        self.input_layout.addWidget(
            self.add_button
        )  # Помещаем кнопку "Добавить" в горизонтальный макет (она встанет справа от поля)

        self.task_list = (
            QListWidget()
        )  # Создаем виджет списка, в котором будут отображаться все добавленные задачи

        self.delete_button = QPushButton(
            "Удалить выбранную задачу"
        )  # Создаем кнопку с надписью для удаления элемента из списка
        self.delete_button.clicked.connect(
            self.delete_task
        )  # Связываем сигнал клика по кнопке удаления с методом self.delete_task

        self.main_layout.addLayout(
            self.input_layout
        )  # Добавляем горизонтальный макет (ввод + кнопка) на самый верх главного вертикального макета
        self.main_layout.addWidget(
            self.task_list
        )  # Добавляем виджет списка в центр главного вертикального макета
        self.main_layout.addWidget(
            self.delete_button
        )  # Добавляем кнопку удаления в самый низ главного вертикального макета

        self.central_widget.setLayout(
            self.main_layout
        )  # Устанавливаем настроенный главный вертикальный макет внутрь центрального контейнера

    def add_task(self):  # Создаем метод-слот для добавления задачи в список
        task_text = (
            self.task_input.text().strip()
        )  # Получаем текст из поля ввода и очищаем его от случайных пробелов по краям
        if (
            task_text
        ):  # Проверяем условие: если строка после очистки оказалась не пустой
            self.task_list.addItem(
                task_text
            )  # Добавляем новый текстовый элемент (задачу) в наш виджет списка QListWidget
            self.task_input.clear()  # Полностью очищаем поле ввода, подготавливая его к новой задаче
        else:  # Если пользователь ничего не ввел и нажал кнопку
            QMessageBox.warning(
                self, "Ошибка", "Нельзя добавить пустую задачу!"
            )  # Показываем предупреждающее модальное окно с текстом ошибки

    def delete_task(self):  # Создаем метод-слот для удаления задачи из списка
        current_item = (
            self.task_list.currentItem()
        )  # Получаем объект текущего выбранного элемента (строки) в списке
        if (
            current_item
        ):  # Проверяем условие: если в списке действительно выделена какая-то строка
            row = self.task_list.row(
                current_item
            )  # Определяем порядковый номер (индекс) выбранной строки в списке
            self.task_list.takeItem(
                row
            )  # Изымаем (удаляем) элемент с этим индексом из виджета списка
        else:  # Если пользователь нажал кнопку удаления, не выбрав ни одну задачу
            QMessageBox.information(
                self, "Внимание", "Пожалуйста, выберите задачу для удаления."
            )  # Выводим информационное окно с подсказкой о необходимости выбора


if (
    __name__ == "__main__"
):  # Проверяем, запущен ли скрипт напрямую, а не импортирован как модуль
    app = QApplication(
        sys.argv
    )  # Создаем экземпляр приложения PySide, передавая ему системные аргументы командной строки
    window = (
        TodoApp()
    )  # Создаем объект нашего главного окна на основе написанного класса TodoApp
    window.show()  # Делаем окно видимым на экране компьютера (по умолчанию при создании окна скрыты)
    sys.exit(
        app.exec()
    )  # Запускаем бесконечный цикл обработки событий Qt и передаем системе код выхода после закрытия окна
