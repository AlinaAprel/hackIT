#Задача: Нарисовать толстый треугольник, используя цвет в формате HEX (например, цвет морской волны #20B2AA).
import turtle

t = turtle.Turtle()
t.shape("turtle")
t.pensize(5)               # Делаем линию толщиной в 5 пикселей

t.pencolor("#20B2AA")      # Задаем цвет контура с помощью HEX-кода

# Рисуем треугольник с помощью цикла
for i in range(3):         # Повторяем 3 раза
    t.forward(150)
    t.left(120)            # 360 / 3 = 120 градусов

turtle.done()