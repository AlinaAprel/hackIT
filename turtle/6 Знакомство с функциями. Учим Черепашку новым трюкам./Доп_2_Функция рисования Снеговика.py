# Задача: Напиши функцию draw_snowman(), которая рисует снеговика из трех кругов 
# один над другим (с помощью t.circle()). В основной программе вызови эту функцию дважды 
# (нарисуй двух снеговиков рядом).
# Подсказка: Чтобы круги рисовались один над другим, после каждого круга нужно делать прыжок вверх.

import turtle
t = turtle.Turtle()
t.speed(0)

def draw_snowman():
    # Нижний ком
    t.circle(40)
    
    # Прыжок вверх
    t.penup()
    t.left(90)
    t.forward(80) # Диаметр нижнего кома (40 * 2)
    t.right(90)
    t.pendown()
    
    # Средний ком
    t.circle(30)
    
    # Прыжок вверх
    t.penup()
    t.left(90)
    t.forward(60) # Диаметр среднего кома
    t.right(90)
    t.pendown()
    
    # Верхний ком (голова)
    t.circle(20)

# Рисуем первого
draw_snowman()

# Прыгаем в сторону
t.penup()
t.goto(150, -50)
t.pendown()

# Рисуем второго
draw_snowman()

turtle.done()