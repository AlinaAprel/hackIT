#Задача: Написать функцию для рисования квадрата и вызвать её один раз.

import turtle

t = turtle.Turtle()
t.shape("turtle")
t.pensize(3)

# 1. СОЗДАЕМ ФУНКЦИЮ (Учим черепашку)
# Назовем её draw_square (нарисовать_квадрат)
def draw_square():
    t.pencolor("blue")
    for i in range(4):     # Отступ для цикла (внутри функции)
        t.forward(50)      # Двойной отступ (внутри цикла, который внутри функции)
        t.left(90)

# --- ЗДЕСЬ ФУНКЦИЯ ЗАКАНЧИВАЕТСЯ (отступов больше нет) ---

# 2. ВЫЗЫВАЕМ ФУНКЦИЮ
draw_square() 

turtle.done()
