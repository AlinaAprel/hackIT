#Задача: Разогнать черепашку до максимума и нарисовать 36 кругов, каждый раз смещаясь на 10 градусов.

import turtle

t = turtle.Turtle()
t.shape("turtle")
t.speed(0)          # 0 - Максимальная скорость!

t.pencolor("blue")

for i in range(36):     # Повторяем 36 раз
    t.circle(80)        # Рисуем круг
    t.right(10)         # Немного поворачиваемся перед следующим кругом

turtle.done()