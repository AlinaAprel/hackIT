#Задача: Напиши программу, которая рисует линии с постоянным поворотом на 90 градусов (как квадрат), 
# но каждая линия становится на 2 пикселя длиннее предыдущей.

import turtle
t = turtle.Turtle()
t.speed(0)
t.pensize(2)

for i in range(100):
    t.forward(i * 2)  # Каждая новая линия чуть длиннее
    t.left(90)        # Прямой угол дает эффект закручивающегося квадрата

turtle.done()